def color_info(color):
    c = _n(color)
    if not c:
        return None
    for keys, tone, lines, rooms in COLORS:
        if any(_n(k) in c for k in keys):
            return {"tone": tone, "lines": lines, "rooms": rooms}
    return None


def style_info(p, design=""):
    cats = " ".join(c.name for c in p.categories.all()) if p.pk else ""
    hay = _n(" ".join([p.title or "", design or "", cats]))
    for key, lines in STYLES:
        if _n(key) in hay:
            return key, lines
    return "", []


def reeds_num(p):
    from .render import spec

    m = re.search(r"\d{3,4}", fa_latin(spec(p, "شانه")) or fa_latin(p.title or ""))
    return int(m.group(0)) if m else 0


def fa_latin(s):
    return (s or "").translate(str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789"))


# ------------------------------------------------------------------ متغیرها
class Smart:
    def __init__(self, ctx):
        self.ctx, self.p = ctx, ctx.p
        self.seed = site_seed(self.p)

    def _pick(self, opts, salt):
        return pick(opts, self.seed, salt)

    def color_line(self):
        from .render import color_of

        color = color_of(self.p)
        info = color_info(color)
        if not info:
            return ""
        head, _, tail = self._pick(info["lines"], "c").partition(" که ")
        return f"زمینهٔ {color}، {head} است که {tail}"

    def style_line(self):
        from .render import design_of

        _, lines = style_info(self.p, design_of(self.p))
        return self._pick(lines, "s")

    def reeds_line(self):
        r = reeds_num(self.p)
        lines = REEDS.get(r)
        if not lines:
            return ""
        return self._pick(lines, "r")

    def material_line(self):
        m = MATERIAL.get(self.p.material)
        return self._pick(m["about"], "m") if m else ""

    def rooms(self):
        from .render import color_of

        info = color_info(color_of(self.p))
        return info["rooms"] if info else ""

    def care(self):
        m = MATERIAL.get(self.p.material)
        return " ".join(m["care"][:3]) if m else ""

    def intro(self):
        """یک پاراگراف معرفی، با جمله‌بندی و ترتیب متفاوت برای هر فرش."""
        from .render import brand_of, color_of, design_of

        p = self.p
        design, color, brand = fa_num(design_of(p)), color_of(p), brand_of(p)
        if not design and not color:
            return ""
        from .render import design_label

        label = design_label(p)
        name = "فرش" + ((f" {label}" if label.startswith("کد ") else f" نقشهٔ {design}") if design else "") + (f" با زمینهٔ {color}" if color else "")
        made = f"کارخانهٔ {brand} در کاشان" if brand else "کاشان"
        opening = self._pick([
            f"{name}، بافت {made} است.",
            f"{name} را {made.replace(' در کاشان', '') if brand else 'کارخانه‌های کاشان'} بافته است.",
            f"{name} یکی از طرح‌های {('کارخانهٔ ' + brand) if brand else 'فرش ماشینی کاشان'} است.",
        ], "o")
        body = [x + "." for x in (self.style_line(), self.color_line()) if x]
        if len(body) == 2 and int(hashlib.md5(f"{self.seed}:ord".encode()).hexdigest()[:2], 16) % 2:
            body.reverse()
        from .render import border_of

        border = border_of(p)
        if border and color:
            if _n(border) == _n(color):
                body.append("حاشیه هم‌رنگ زمینه است و فرش یکدست و آرام دیده می‌شود.")
            else:
                body.append(self._pick([f"حاشیهٔ {border} دور زمینه قابی مشخص می‌کشد و فرش را در اتاق پررنگ‌تر نشان می‌دهد.",
                                        f"حاشیهٔ {border}، زمینهٔ {color} را قاب گرفته و به فرش جلوهٔ بیشتری داده است."], "b"))
        for x in (self.reeds_line(), self.material_line()):
            if x:
                body.append(x + ".")
        if "برجسته" in (p.title or ""):
            body.append(self._pick(["گل‌ها برجسته بافته شده‌اند و نقش‌ها عمق بیشتری پیدا می‌کنند.",
                                    "بافت گل برجسته، نقش‌ها را از زمینه جدا می‌کند و به فرش حالتی سه‌بعدی می‌دهد."], "e"))
        rooms = self.rooms()
        if rooms:
            body.append(self._pick([f"برای {rooms} انتخاب مناسبی است.", f"جای مناسب این فرش: {rooms}."], "rm"))
        return " ".join([opening, *body])

    def get(self, name):
        return {
            "معرفی": self.intro, "سبک": self.style_line, "حس_رنگ": self.color_line, "کیفیت_شانه": self.reeds_line,
            "جنس_توضیح": self.material_line, "مناسب_برای": self.rooms, "نگهداری": self.care,
        }.get(name, lambda: None)()


