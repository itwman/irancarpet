"""متن هوشمند فرش: جمله‌های متنوع از روی ویژگی‌های واقعی هر فرش.

دو ابزار:
  {{الف|ب|ج}}   در قالب: برای هر فرش یکی از گزینه‌ها (ثابت برای همان فرش)، تا متن صفحه‌ها تکراری نشود.
  متغیرهای هوشمند: {معرفی} {سبک} {حس_رنگ} {کیفیت_شانه} {جنس_توضیح} {مناسب_برای} {نگهداری}

هیچ ادعای تازه‌ای ساخته نمی‌شود: هر جمله فقط وقتی می‌آید که داده‌اش (رنگ، شانه، جنس، نقشه) روی فرش ثبت شده باشد.
"""
import hashlib
import re

from core.templatetags.fa import fa_num

VARIANT_RE = re.compile(r"\{\{((?:[^{}]|\{[^{}]*\})*)\}\}")


# ------------------------------------------------------------------ انتخاب ثابت برای هر فرش
def site_seed(p):
    """دانهٔ انتخاب جمله‌ها برای هر فرش. روی سایت دوم (مثل فرشستان) نام قالب سایت هم در آن است تا
    همان فرش در دو سایت جمله‌بندی دیگری بگیرد؛ روی ایران کارپت (بدون قالب) همان قبلی می‌ماند."""
    from django.conf import settings

    base = p.pk or p.title
    theme = getattr(settings, "SITE_THEME", "")
    return f"{theme}:{base}" if theme else base


def pick(options, seed, salt=""):
    """یکی از گزینه‌ها؛ برای یک فرش همیشه همان (با تغییر قیمت یا ذخیرهٔ دوباره عوض نمی‌شود)."""
    options = [o for o in options if o]
    if not options:
        return ""
    h = int(hashlib.md5(f"{seed}:{salt}".encode()).hexdigest()[:8], 16)
    return options[h % len(options)]


def _split_top(s):
    """«الف|ب {لینک:x|y}» ← ['الف', 'ب {لینک:x|y}'] — | داخل آکولاد جداکننده نیست."""
    out, cur, depth = [], [], 0
    for ch in s:
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        if ch == "|" and depth == 0:
            out.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    out.append("".join(cur))
    return [x.strip() for x in out]


def variants(line, seed, salt=""):
    """{{الف|ب}} های یک خط قالب ← یک گزینه."""
    n = [0]

    def rep(m):
        n[0] += 1
        return pick(_split_top(m.group(1)), seed, f"{salt}:{n[0]}")
    return VARIANT_RE.sub(rep, line)


# ------------------------------------------------------------------ دانش رنگ، نقشه و جنس
def _n(s):
    s = (s or "").replace("ي", "ی").replace("ك", "ک").replace("‌", "").replace(" ", "").replace("آ", "ا")
    return s

