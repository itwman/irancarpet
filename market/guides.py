def setup_steps(seller):
    """فهرست راه‌اندازی فروشگاه تازه؛ وقتی همه انجام شد پنهان می‌شود."""
    from catalog.models import Product
    from pricing.models import Album

    prods = Product.objects.filter(seller=seller)
    rows = [
        ("لوگوی فروشگاه", "/seller/look/", bool(seller.logo_id)),
        ("کاور یا اسلاید ویترین", "/seller/look/", bool(seller.cover_id) or seller.slides.exists()),
        ("یک جملهٔ معرفی و «دربارهٔ ما»", "/seller/look/", bool(seller.tagline and seller.about)),
        ("اولین آلبوم قیمت", "/seller/albums/", Album.all_objects.filter(seller=seller).exists()),
        ("دست‌کم ۳ کالا", "/seller/quick/", prods.count() >= 3),
        ("یک قفسه برای ویترین", "/seller/shelves/", seller.shelves.exists()),
        ("شبای حساب برای تسویه", "/seller/settings/", bool(seller.sheba)),
    ]
    steps = [{"text": t, "url": u, "done": d} for t, u, d in rows]
    done = sum(s["done"] for s in steps)
    return {"steps": steps, "done": done, "total": len(steps), "pct": round(done * 100 / len(steps)), "all": done == len(steps)}
