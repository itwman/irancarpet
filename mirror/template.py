def ensure_template(s):
    """بار اول که همگام‌سازی روشن می‌شود: قالب فرشستان پیش‌فرض این سایت می‌شود."""
    if s.template_ready:
        return None
    from content.models import ContentTemplate
    from content.render import clear_cache

    with transaction.atomic():
        t = ContentTemplate.objects.filter(name=NAME).first()
        if t is None:
            ContentTemplate.objects.filter(is_default=True).update(is_default=False)
            t = ContentTemplate.objects.create(name=NAME, is_default=True, bullets=BULLETS, body=BODY)
        type(s).objects.filter(pk=s.pk).update(template_ready=True)
        s.template_ready = True
    clear_cache()
    return t
