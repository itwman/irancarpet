def _first(first_name):
    t = (first_name or "").replace("ي", "ی").replace("ك", "ک").replace("‌", "").strip()
    t = re.sub(r"^(سید|سیده|میر)\s*", "", t) if t not in MALE and t not in FEMALE else t
    return t.split()[0] if t.split() else ""


def guess(first_name, last_name=""):
    full = f"{first_name} {last_name}"
    if any(w in full for w in COMPANY_WORDS):
        return "co"
    raw = (first_name or "").replace("‌", "").strip()
    if raw.startswith("سیده"):
        return "mrs"
    f = _first(first_name)
    if f in MALE and f not in FEMALE:
        return "mr"
    if f in FEMALE and f not in MALE:
        return "mrs"
    return ""
